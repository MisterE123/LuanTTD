#!/usr/bin/env python3
"""Generate exact stock industry specs and climate cargo rows, without art."""
import argparse
from hashlib import sha256
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]
OUTPUT=ROOT/"mods/luanttd_core/openttd/stock_industry_specs_rc1.lua"
p=argparse.ArgumentParser(description=__doc__)
p.add_argument("upstream",type=Path)
p.add_argument("--check",action="store_true")
args=p.parse_args()

def read(name,checksum):
    raw=(args.upstream/"src"/name).read_bytes()
    assert sha256(raw).hexdigest()==checksum,name
    return raw.decode()
def without_comments(s):
    return re.sub(r"//[^\n]*|/\*.*?\*/","",s,flags=re.S)
def call(s,start):
    """Split the contents of a stock C++ macro call respecting its nested values."""
    stack=[]
    out=[]
    current=start
    for j in range(start,len(s)):
        c=s[j]
        if c in "([{":stack.append(c)
        elif c in ")]}":
            if stack:assert "([{".index(stack.pop())==")]}".index(c)
            else:
                assert c==")"
                return out+[s[current:j].strip()]
        elif c=="," and not stack:
            out.append(s[current:j].strip())
            current=j+1
    raise ValueError("unterminated macro")
def lua(x):
    if x is None:return "false"
    if isinstance(x,bool):return str(x).lower()
    if isinstance(x,str):
        assert '"' not in x and '\\' not in x
        return '"'+x+'"'
    if isinstance(x,(tuple,list)):return "{"+",".join(lua(y) for y in x)+"}"
    return str(x)

industry=without_comments(read("table/build_industry.h","eb7938fd37dd37854927253f2f3beeed3c6cafa7425d959035cefef149b66056"))
cargo=without_comments(read("table/cargo_const.h","cac711a29f0bcd906a8c202219ead4ba5cec90bfc5ea2e2fc03c990ab86f43d2"))
newgrf=read("newgrf.cpp","e6176f8d13d7f57139f134f69630327dd3300a6b3b7979bbb1d9e6294b2b344e")
ids={k:int(n) for k,n in re.findall(r"^\s*(IT_\w+)\s*=\s*(\d+),",industry,re.M)}
climates=("Temperate","Arctic","Tropic","Toyland")
def stock_label(v):
    return None if v=="CT_INVALID" else v

rows=[]
for m in re.finditer(r"\bMI\((?=_tile_table_)",industry):
    f=call(industry,m.end())
    assert len(f)==36,(len(f),f)
    climates_mask=sum(1<<i for i,c in enumerate(climates) if "LandscapeType::"+c in f[29])
    conflicts=[ids[id_] for id_ in f[13:16] if id_!="IT_INVALID"]
    f_out=[[stock_label(f[i]),int(f[i+1])] for i in (17,19)]
    f_in=[[stock_label(f[i]),int(f[i+1])] for i in (22,24,26)]
    flags=re.findall(r"IndustryBehaviour::(\w+)",f[30])
    rows.append([f[0].removeprefix("_tile_table_"),int(f[2]),int(f[3],0),
                 list(map(int,f[4:8])),list(map(int,f[8:12])),int(f[12]),
                 conflicts,f[16].split("::")[-1],f_out,int(f[21]),f_in,
                 f[28].split("::")[-1],climates_mask,flags])
assert len(rows)==37 and all(r[12] for r in rows)
def_cargo=[]
for m in re.finditer(r"\bMK\((?=\s*(?:\d|0x))",cargo):
    f=call(cargo,m.end())
    assert len(f)==14
    label=stock_label(f[1])
    effect=f[9].split("::")[-1]
    classes=re.findall(r"CargoClass::(\w+)",f[13])
    def_cargo.append([label,int(f[0],0),int(f[2]),int(f[3]),int(f[4],0),
                      int(f[5]),int(f[6]),int(f[7]),f[8]=="true",effect,classes])
assert len(def_cargo)==35
climate_input=cargo.split("_default_climate_cargo[NUM_LANDSCAPE][NUM_ORIGINAL_CARGO] = {",1)[1].split("\n};",1)[0]
climate_rows=[]
for line in re.findall(r"\{([^{}]+)\}",climate_input):
    slots=[s.strip() for s in line.split(",") if s.strip()]
    assert len(slots)==12
    climate_rows.append([int(a) if a.isdigit() else next(i for i,r in enumerate(def_cargo) if a==r[0]) for a in slots])
assert len(climate_rows)==4
groups={k:[a.strip() for a in v.split(",")]
        for k,v in re.findall(r"case (MCT_\w+): return GetActiveCargoLabel\(\{(.*?)\}\);",newgrf)}
assert len(groups)==3
o=["-- SPDX-License-Identifier: GPL-2.0-only",
   "-- OpenTTD contributors, 16.0-RC1 build_industry.h, cargo_const.h and newgrf.cpp.",
   "-- Generated by tools/build_stock_industry_specs_rc1.py. Data only.",
   "return {",
   "  -- key, cost, prospect, appearance, generation, color, conflicts, check,",
   "  -- produced slot labels/rates, minimum, accepted labels/multipliers,",
   "  -- life, climate mask, behavior labels.",
   "  industry={"]
for i,r in enumerate(rows):o.append(f"    [{i}]={lua(r)},")
o.extend(("  },","  -- label, bit number, color, weight, capacity, payment, age1/age2, freight, effect, classes.",
          "  default_cargo={"))
for i,r in enumerate(def_cargo):o.append(f"    [{i}]={lua(r)},")
o.extend(("  },","  climate_slots={"))
for k,r in zip(climates,climate_rows):o.append(f"    {k.lower()}={lua(r)},")
o.extend(("  },","  groups={"))
for k,r in sorted(groups.items()):o.append(f"    {k}={lua(r)},")
o.extend(("  },","}"))
expected="\n".join(o)+"\n"
if args.check:assert OUTPUT.read_text()==expected,"Stock industry specs out of sync"
else:OUTPUT.write_text(expected)
print("PASS stock RC1 37 firm specs, 35 cargo definitions, and four climate slot maps")
