#!/usr/bin/env python3
"""Author Original survey shore meshes from LuanTTD's own terrain and art.

The settled ground stays on exactly the existing LuanTTD planar triangles.
An original dry/wet shingle strip and a separate level clipped water surface
provide shoreline appearance without bending the sea up a raised corner.
"""
import argparse
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1] / "mods" / "bayline"
MASKS = (1, 2, 3, 4, 6, 7, 8, 9, 11, 12, 13, 14, 23, 27, 29, 30)
SEA = -0.488
SHINGLE = -0.365


def source(mask):
    rows = (ROOT / "models" / f"bl_land_{mask}.obj").read_text().splitlines()
    vertices = [tuple(map(float, s.split()[1:])) for s in rows if s.startswith("v ")]
    return [[vertices[int(v.split("/")[0]) - 1] for v in s.split()[1:]]
            for s in rows if s.startswith("f ")]


def section(polygon, level, lower):
    def inside(p):
        return p[1] <= level if lower else p[1] >= level

    result = []
    for a, b in zip(polygon[-1:] + polygon[:-1], polygon):
        if inside(a) != inside(b):
            t = (level - a[1]) / (b[1] - a[1])
            result.append((a[0] + (b[0] - a[0]) * t, level, a[2] + (b[2] - a[2]) * t))
        if inside(b):
            result.append(b)
    return result


def normals_2d(a, b, c):
    return (b[0]-a[0])*(c[2]-a[2]) - (b[2]-a[2])*(c[0]-a[0])


def geometry(mask, width):
    points, faces = [], []

    def add(poly, kind):
        for i in range(1, len(poly) - 1):
            a, b, c = poly[0], poly[i], poly[i+1]
            if abs(normals_2d(a, b, c)) <= 1e-8:
                continue
            face = []
            for x,y,z in (a,b,c):
                u, v = (0.5-x)/2, (1.5-z)/2
                face.append(len(points)+1)
                points.append((x,y,z, (kind*width+.5+u*(width-1))/(3*width), v))
            faces.append(face)

    for p in source(mask):
        if mask:
            add(section(p, SHINGLE, False),0)
            add(section(section(p, SHINGLE, True), SEA, False),1)
            add([(x,SEA,z) for x,_,z in section(p,SEA,True)],2)
        else:
            add([(x,SEA,z) for x,_,z in p],2)
    lines = ["# Original LuanTTD coast; generated by tools/build_original_coast_art.py", "o Coast"]
    lines += [f"v {x:.8f} {y:.8f} {z:.8f}" for x,y,z,_,_ in points]
    lines += [f"vt {u:.8f} {v:.8f}" for _,_,_,u,v in points]
    lines += ["f " + " ".join(f"{i}/{i}" for i in f) for f in faces]
    return ("\n".join(lines)+"\n").encode()


def build():
    found = {}
    def tex(name):
        return Image.open(ROOT/"textures"/f"bl_{name}.png").convert("RGB")
    sea=tex("water3")
    width,height=sea.size
    for j in range(4):
        grass=tex(f"grass{j}")
        assert grass.size==sea.size
        a=Image.new("RGB",(width*3,height))
        a.paste(grass,(0,0));a.paste(sea,(2*width,0))
        for y in range(height):
            for x in range(width):
                n=(x*23 + y*17 + (x*y+11)*7) % 13 - 6
                a.putpixel((width+x,y),(151+n*2,140+n*2,105+n))
        from io import BytesIO
        out=BytesIO()
        a.save(out,format="PNG",optimize=True)
        found[ROOT/"textures"/f"bl_original_coast_{j}.png"]=out.getvalue()
    for s in (0,*MASKS):
        found[ROOT/"models"/f"bl_original_coast_{s}.obj"]=geometry(s,width)
    return found


if __name__ == "__main__":
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check",action="store_true")
    opts=p.parse_args()
    for path,data in build().items():
        if opts.check:
            assert path.read_bytes()==data, f"{path.name} differs from source"
        else:
            path.write_bytes(data)
