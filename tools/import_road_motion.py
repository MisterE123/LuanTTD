#!/usr/bin/env python3
"""Regenerate Lua road data from an unmodified OpenTTD 14.1 movement header."""
from pathlib import Path
import argparse
import hashlib
import subprocess
import tempfile

SHIM = """#include <cstdio>
using byte = unsigned char;
enum {DIAGDIR_NE, DIAGDIR_SE, DIAGDIR_SW, DIAGDIR_NW};
enum {RDE_NEXT_TILE = 128, RDE_TURNED = 64};
struct RoadDriveEntry { byte x, y; };
#include "roadveh_movement.h"
int main() {
  for (auto row : _road_road_drive_data) {
    for (unsigned frame = 0;; ++frame) {
      const auto rd = row[frame];
      std::printf("%s%d,%d", frame ? "," : "", rd.x, rd.y);
      if (rd.x & (RDE_NEXT_TILE | RDE_TURNED)) break;
    }
    std::puts("");
  }
  for (auto frame : _road_stop_stop_frame) std::printf("%d,", frame);
  std::puts("");
}
"""


def generate(header):
    with tempfile.TemporaryDirectory() as directory:
        tmp = Path(directory)
        (tmp / "roadveh_movement.h").write_bytes(header.read_bytes())
        (tmp / "dump.cpp").write_text(SHIM)
        subprocess.run(["c++", "-std=c++17", "-Wall", "-Wextra", "-Werror",
                        str(tmp / "dump.cpp"), "-o", str(tmp / "dump")], check=True)
        rows = subprocess.check_output([str(tmp / "dump")], text=True).splitlines()
    assert len(rows) == 65
    digest = hashlib.sha256(header.read_bytes()).hexdigest()
    out = [
        "-- Generated by tools/import_road_motion.py from OpenTTD 14.1",
        "-- src/table/roadveh_movement.h (OpenTTD contributors).",
        "-- SPDX-License-Identifier: GPL-2.0-only",
        "-- See COPYING.OpenTTD.md. Upstream SHA-256: " + digest,
        "-- Flat pairs retain the original flag bytes. Index keys are zero-based.",
        "return {",
        "  road={",
    ]
    for i, row in enumerate(rows[:-1]):
        out.append(f"    {'[0]=' if i == 0 else ''}{{{row}}},")
    out += ["  },", f"  bay_stop_frame={{[0]={rows[-1]}}},", "}", ""]
    return "\n".join(out)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("header", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    out = Path(__file__).resolve().parents[1] / "mods/luanttd_core/openttd/road_motion_data.lua"
    expected = generate(args.header)
    if args.check:
        if out.read_text() != expected:
            raise SystemExit("Road motion data differ from the compiled source")
        print("PASS: all 64 motion rows and 32 bay stop frames match OpenTTD")
    else:
        out.write_text(expected)
