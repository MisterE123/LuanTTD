#!/usr/bin/env python3
"""Conform the original Blender tram rail and wire meshes to stock inclines.

Luanti flips OBJ X. Road meshes place the surface in voxel base+1.
Place the tram overlay at base+2 and subtract one from every vertex so
both remain separate meshes without moving rails away from the road.
Signed streets occupy base+2 with their markings. The second overlay
mounts at base+3 with the same world-space geometry.
"""
import argparse
import math
from pathlib import Path

MODELS=Path(__file__).resolve().parents[1]/"mods/luanttd_core/models"
# grade : existing atlas mesh, dY/dOBJ_X, dY/dOBJ_Z, height at OBJ origin
PLANES={3:(10,-.5,0,.25),6:(5,0,.5,.25),9:(5,0,-.5,.75),12:(10,.5,0,.75)}


def variant(grade, offset=1):
    bits,a,b,c=PLANES[grade]
    lines=["# Generated by tools/build_tram_grade_art.py from original LuanTTD Blender meshes"]
    for line in (MODELS/f"bl_tramway_{bits}.obj").read_text().splitlines():
        if line.startswith("v "):
            x,y,z=map(float,line.split()[1:])
            line=f"v {x:.6f} {y-offset+a*x+b*z+c:.6f} {z:.6f}"
        elif line.startswith("vn "):
            x,y,z=map(float,line.split()[1:])
            x,z=x-a*y,z-b*y
            length=math.sqrt(x*x+y*y+z*z)
            line=f"vn {x/length:.6f} {y/length:.6f} {z/length:.6f}"
        lines.append(line)
    return "\n".join(lines)+"\n"


def level_crossing(axis):
    bits={0:10,1:5}[axis]
    lines=["# Original flat tram mesh translated for the crossing host voxel"]
    for line in (MODELS/f"bl_tramway_{bits}.obj").read_text().splitlines():
        if line.startswith("v "):
            x,y,z=map(float,line.split()[1:])
            line=f"v {x:.6f} {y-1:.6f} {z:.6f}"
        lines.append(line)
    return "\n".join(lines)+"\n"


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument("--check",action="store_true")
    args=parser.parse_args()
    for grade in PLANES:
        for offset,suffix in ((1,""),(2,"_signed")):
            target=MODELS/f"bl_tramway_grade_{grade}{suffix}.obj"
            content=variant(grade,offset)
            if args.check:
                assert target.read_text()==content,target
            elif not target.exists() or target.read_text()!=content:
                target.write_text(content)
    for axis in range(2):
        target=MODELS/f"bl_tramway_crossing_{axis}.obj"
        content=level_crossing(axis)
        if args.check:
            assert target.read_text()==content,target
        elif not target.exists() or target.read_text()!=content:
            target.write_text(content)
    print("PASS original tram rails, wires and masts match four source inclines and both level crossing axes")


if __name__=="__main__":
    main()
