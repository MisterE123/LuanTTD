#!/usr/bin/env python3
"""Translate the remaining stock airport layouts and state tables, in source order.

Usage: python3 tools/emit_rc1_large_airports.py PATH_TO_OPENTTD_16.0-RC1 [--check]
The emitted GPL data are not evidence that these airports are yet playable.
"""
import argparse
import re
from collections import defaultdict
from pathlib import Path
from subprocess import check_output

RC1 = "07b339c0aaeb0a87be9490b2f1c3f17c6b00b837"
AIRPORTS = ("metropolitan", "commuter", "international", "intercontinental")
DIRECTIONS = {k: i for i,k in enumerate(("N","NE","E","SE","S","SW","W","NW"))}
ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "mods/luanttd_core/openttd/airport_expansion_data.lua"


def strip_comments(text):
    return re.sub(r"/\*.*?\*/|//[^\n]*", "", text, flags=re.S)


def body(src, name, prefix=""):
    # Both initializer-list and standard array syntax are used upstream.
    found = re.search(prefix + r"\b" + re.escape(name) + r"\s*(?:\[[^]]*\])?\s*=\s*\{(.*?)\};", src, re.S)
    if not found:
        raise ValueError(f"missing pinned stock table {name}")
    return found[1]


def enum(src,name):
    body_ = re.search(r"\benum(?:\s+class)?\s+"+name+r"\s*:[^\{]+\{(.*?)\};",src,re.S)
    if not body_:
        raise ValueError(name)
    out, n = {}, -1
    for term in body_[1].split(","):
        k,sep,v = term.strip().partition("=")
        if not k:
            continue
        n = int(v.strip()) if sep else n+1
        out[k.strip()] = n
    return out


def fields(src, pat):
    rows = list(re.finditer(pat,src))
    leftover = re.sub(pat,"",src)
    if leftover.strip(" \r\t\n,"):
        raise ValueError("unhandled stock table markup: "+leftover[:250])
    return [r.groups() for r in rows]


def as_mask(value, cat, names):
    ids = re.findall(cat+r"::(\w+)",value)
    left = re.sub(cat+r"::\w+","",value)
    if left.strip(" \r\t\n{},"):
        raise ValueError("unhandled bit notation "+value)
    return sum({1 << names[name] for name in ids})


def rows(xs):
    return "{"+",".join(str(x) for x in xs)+"}"


def make(upstream):
    if (upstream/".git").exists() and check_output(
        ["git","-C",str(upstream),"rev-parse","HEAD"],text=True).strip()!=RC1:
        raise ValueError("expected pinned OpenTTD 16.0-RC1 "+RC1)
    root = upstream / "src"
    hdr = strip_comments((root/"airport.h").read_text())
    blocks, flags, states = (enum(hdr,name) for name in
        ("AirportBlock","AirportMovingDataFlag","AirportMovementStates"))
    tiles = enum(strip_comments((root/"table/airporttile_ids.h").read_text()),"AirportTiles")
    airport = strip_comments((root/"airport.cpp").read_text())
    aircraft = strip_comments((root/"aircraft_cmd.cpp").read_text())
    mapping = fields(body(aircraft,"_airport_terminal_mapping"),
        r"\{\s*(\w+)\s*,\s*AirportBlock::(\w+)\s*\}")
    slots = [(states[state],1<<blocks[block]) for state,block in mapping]
    assert len(slots)==11
    moves = strip_comments((root/"table/airport_movement.h").read_text())
    defs = strip_comments((root/"table/airport_defaults.h").read_text())
    lua = ["-- SPDX-License-Identifier: GPL-2.0-only", "-- OpenTTD contributors.",
        "-- Generated by tools/emit_rc1_large_airports.py from OpenTTD 16.0-RC1.",
        "-- Direct tables; these are not mounted as playable airports yet.", "return {"]
    for name in AIRPORTS:
        specpat = r"\bAS\("+name+r"\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*CalendarTime::MAX_YEAR\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)"
        w,h,year,catch,noise,maint = map(int,re.search(specpat,defs).groups())
        layout = body(defs,"_tile_table_"+name+"_0")
        layout_rows = fields(layout,r"\{\{\s*(\d+)\s*,\s*(\d+)\s*\}\s*,\s*(APT_\w+)\s*\}")
        assert len({(int(x),int(z)) for x,z,_ in layout_rows}) == len(layout_rows)
        assert all(0<=int(x)<w and 0<=int(z)<h for x,z,_ in layout_rows)
        depot_rows = fields(body(moves,"_airport_depots_"+name),
            r"\{\{\s*(\d+)\s*,\s*(\d+)\s*\}\s*,\s*Direction::(\w+)\s*,\s*(\d+)\s*\}")
        terminals = list(map(int,body(moves,"_airport_terminal_"+name).split(",")))
        assert terminals[0] == len(terminals)-1
        entry_raw = list(map(int,body(moves,"_airport_entries_"+name).split(",")))
        assert len(entry_raw)==4
        points = fields(body(moves,"_airport_moving_data_"+name),
            r"\{\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(\{[^}]*\})\s*,\s*Direction::(\w+)\s*\}")
        transitions = fields(body(moves,"_airport_fta_"+name),
            r"\{\s*(\d+|MAX_ELEMENTS)\s*,\s*(\w+)\s*,\s*(\{[^}]*\}|AirportBlock::\w+)\s*,\s*(\d+)\s*\}")
        assert transitions[-1] == ("MAX_ELEMENTS","TO_ALL","{}","0")
        by_position = defaultdict(list)
        for at,action,bb,target in transitions[:-1]:
            by_position[int(at)].append((int(action) if action.isdigit() else states[action],
                as_mask(bb,"AirportBlock",blocks),int(target)))
        assert list(by_position)==list(range(len(points)))
        assert all(t < len(points) for rr in by_position.values() for _,_,t in rr)
        assert all(t < len(points) for t in entry_raw)
        pad,short = re.search(r"\bAIRPORT\("+name+r"\s*,\s*(\d+)\s*,\s*(true|false)\)",airport).groups()
        lua.append(f"  {name}={{W={w},H={h},intro_year={year},catchment={catch},noise={noise},maintenance={maint},")
        lua.append(f"    num_helipads={pad}, short_strip={short},")
        lua.append("    terminal_mapping={"+",".join(rows(r) for r in slots)+"},")
        lua.append("    hangars={"+",".join(rows((x,z,DIRECTIONS[d],i)) for x,z,d,i in depot_rows)+"},")
        lua.append("    terminal_groups="+rows(terminals[1:])+", entries={[0]="+",".join(map(str,entry_raw))+"},")
        lua.append("    tiles={")
        for x,z,t in layout_rows:
            lua.append(f'      {{{x},{z},{tiles[t]}}}, -- {t}')
        lua.append("    },")
        lua.append("    points={")
        for i,(x,z,fs,d) in enumerate(points):
            lua.append("      "+("[0]=" if i==0 else "")+rows((x,z,as_mask(fs,"AirportMovingDataFlag",flags),DIRECTIONS[d]))+",")
        lua.append("    },")
        lua.append("    layout={")
        for i,rr in by_position.items():
            lua.append("      "+("[0]=" if i==0 else "")+"{"+",".join(rows(r) for r in rr)+"},")
        lua.extend(("    },","  },"))
    return "\n".join([*lua,"}",""])


if __name__ == "__main__":
    a = argparse.ArgumentParser(description=__doc__)
    a.add_argument("upstream",type=Path)
    a.add_argument("--check",action="store_true")
    args = a.parse_args()
    art = make(args.upstream)
    if args.check:
        if DEST.read_text()!=art:
            raise SystemExit("Airport tables differ from the pinned source.")
    else:
        tmp=DEST.with_suffix(".tmp")
        tmp.write_text(art)
        tmp.replace(DEST)
    print("Stock airport source data verified:", ", ".join(AIRPORTS))
