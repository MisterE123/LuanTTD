#!/usr/bin/env python3
"""Compile and regenerate movement data from OpenTTD 14.1 roadveh_movement.h."""
import argparse
import hashlib
from pathlib import Path
import subprocess
import tempfile

SHIM = """#include <cstdio>
using byte = unsigned char;
enum { DIAGDIR_NE, DIAGDIR_SE, DIAGDIR_SW, DIAGDIR_NW };
enum { RDE_NEXT_TILE = 128, RDE_TURNED = 64 };
struct RoadDriveEntry { byte x, y; };
#include "roadveh_movement.h"
int main() {
    for (auto row : _road_tram_drive_data) {
        if (row != nullptr) {
            for (unsigned f = 0;; ++f) {
                auto rd = row[f];
                std::printf("%s%d,%d", f ? "," : "", rd.x, rd.y);
                // The eight tram turn rows contain a mid-row TURNED marker,
                // not a terminator, followed by a real return-drive sequence.
                if (rd.x & RDE_NEXT_TILE) break;
            }
        }
        std::puts(row == nullptr ? "false" : "");
    }
}
"""


def generate(header):
    with tempfile.TemporaryDirectory() as directory:
        tmp = Path(directory)
        (tmp / header.name).write_bytes(header.read_bytes())
        (tmp / "dump.cpp").write_text(SHIM)
        subprocess.run(["c++", "-std=c++17", "-Wall", "-Wextra", "-Werror",
                        str(tmp / "dump.cpp"), "-o", str(tmp / "dump")], check=True)
        rows = subprocess.check_output([str(tmp / "dump")], text=True).splitlines()
    assert len(rows) == 65 and rows.count("false") == 33
    assert all(tuple(map(int, rows[i].split(",")))[40] & 64
               for i in (6,7,14,15,22,23,30,31))
    lines = [
        "-- Generated by tools/import_tram_motion.py from OpenTTD 14.1",
        "-- src/table/roadveh_movement.h (OpenTTD contributors).",
        "-- SPDX-License-Identifier: GPL-2.0-only",
        "-- See COPYING.OpenTTD.md. Upstream SHA-256: "+hashlib.sha256(header.read_bytes()).hexdigest(),
        "-- Flat pairs retain TURNED and NEXT_TILE flag bytes; indices are zero-based.",
        "return {",
    ]
    for i, row in enumerate(rows):
        lines.append("  "+("[0]=" if i == 0 else "")+("false" if row=="false" else "{"+row+"}")+",")
    return "\n".join([*lines,"}",""])


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("header",type=Path)
    parser.add_argument("--check",action="store_true")
    args=parser.parse_args()
    out=Path(__file__).resolve().parents[1]/"mods/bayline/openttd/tram_motion_data.lua"
    content=generate(args.header)
    if args.check:
        assert out.read_text()==content,"Tram motion rows differ from compiled stock header"
        print("PASS: 32 OpenTTD tram rows including all eight complete turn tables, plus 33 null entries")
    else:
        out.write_text(content)


if __name__=="__main__":
    main()
