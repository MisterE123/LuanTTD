-- Reproducible meshes of the OpenTTD slope port's continuous height field.
-- Run from game root: lua5.1 tools/build_terrain_meshes.lua
local T=dofile("mods/bayline/openttd/slope.lua")
local out="mods/bayline/models/bl_land_"
-- Join opposite corners at the crease. Without a crease either diagonal
-- triangulates the exact plane. OBJ X is inverted by the Luanti importer.
local diagonal_we={[8]=true,[2]=true,[10]=true,[13]=true,[7]=true}
local uv={{0,0},{1,0},{0,1},{1,1}}
for mask=0,30 do
  if mask<15 or mask==23 or mask==27 or mask==29 or mask==30 then
    local file=assert(io.open(out..mask..".obj","w"))
    file:write("# Generated by tools/build_terrain_meshes.lua\no Terrain\n")
    for _,p in ipairs(uv) do
      file:write(("v %g %g %g\n"):format(.5-2*p[1],T.surface(p[1],p[2],mask)-.5,2*p[2]-.5))
    end
    for _,p in ipairs(uv) do file:write(("vt %g %g\n"):format(p[1],1-p[2])) end
    local triangles=diagonal_we[mask] and {{1,2,3},{2,4,3}} or {{1,2,4},{1,4,3}}
    for _,a in ipairs(triangles) do
      local b,c,d=uv[a[1]],uv[a[2]],uv[a[3]]
      for iu=0,10 do for iv=0,10-iu do
        local u,v,w=iu/10,iv/10,1-(iu+iv)/10
        local x,z=u*b[1]+v*c[1]+w*d[1],u*b[2]+v*c[2]+w*d[2]
        local y=u*T.surface(b[1],b[2],mask)+v*T.surface(c[1],c[2],mask)+w*T.surface(d[1],d[2],mask)
        assert(math.abs(y-T.surface(x,z,mask))<1e-8,"Wrong mesh crease for slope "..mask)
      end end
      file:write(("f %d/%d %d/%d %d/%d\n"):format(a[1],a[1],a[2],a[2],a[3],a[3]))
    end
    file:close()
  end
end
print("PASS: all 19 OpenTTD terrain meshes match the slope sampler")
