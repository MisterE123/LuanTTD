#!/usr/bin/env python3
"""Combine flange, contact-wire and mast assets into one Luanti node per tile."""
from pathlib import Path

MODELS = Path(__file__).resolve().parents[1] / "mods/luanttd_core/models"
TYPES = ("v", "vt", "vn")


def merge(sources):
    count = [0] * len(TYPES)
    result = ["# Generated by tools/combine_tramway.py"]
    for name in sources:
        offset = count.copy()
        result.append(f"o {name}")
        for line in (MODELS / ("bl_" + name + ".obj")).read_text().splitlines():
            kind, _, rest = line.partition(" ")
            if kind in TYPES:
                count[TYPES.index(kind)] += 1
                result.append(line)
            elif kind == "f":
                # Blender inputs use positive 1-based vertex/uv/normal indices.
                result.append("f " + " ".join("/".join(str(int(n) + delta)
                                                        for n, delta in zip(face.split("/"), offset, strict=True))
                                              for face in rest.split()))
    return "\n".join(result) + "\n"


if __name__ == "__main__":
    for mask in range(1, 16):
        path = MODELS / f"bl_tramway_{mask}.obj"
        mast = ["tram_mast_ew" if mask & 10 else "tram_mast_ns"]
        path.write_text(merge([f"tram_rails_{mask}", f"tram_wire_{mask}", *mast]))
