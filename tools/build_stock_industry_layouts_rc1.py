#!/usr/bin/env python3
"""Extract the stock RC1 layout table, not graphics, into the Lua catalog."""
import argparse
from hashlib import sha256
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/"mods/luanttd_core/openttd/stock_industry_layouts_rc1.lua"
DIGEST="eb7938fd37dd37854927253f2f3beeed3c6cafa7425d959035cefef149b66056"
P=argparse.ArgumentParser(description=__doc__)
P.add_argument("upstream",type=Path)
P.add_argument("--check",action="store_true")
args=P.parse_args()
raw=(args.upstream/"src/table/build_industry.h").read_bytes()
assert sha256(raw).hexdigest()==DIGEST,"Not the stock OpenTTD 16.0-RC1 layout file"
src=raw.decode()
types=re.findall(r"^\s*MI\(_tile_table_(\w+),",src,re.M)
assert len(types)==37
out=["-- SPDX-License-Identifier: GPL-2.0-only",
     "-- OpenTTD contributors, 16.0-RC1 src/table/build_industry.h.",
     "-- Generated by tools/build_stock_industry_layouts_rc1.py. No artwork.",
     "-- IDs are zero-based. A gfx of 65535 checks water and places no industry tile.",
     "return {"]
layout_count=cell_count=0
for type_id,name in enumerate(types):
    vec=re.search(rf"std::vector<IndustryTileLayout> _tile_table_{name} \{{(.*?)\n\}};",src,re.S)
    assert vec,name
    ident=re.findall(r"_tile_table_\w+",vec[1])
    out.append(f"  [{type_id}]={{ -- {name}")
    for variant,ref in enumerate(ident):
        tab=re.search(rf"IndustryTileLayout {ref} \{{(.*?)\n\}};",src,re.S)
        assert tab,ref
        triplets=[]
        for x,z,g in re.findall(r"\{\{\s*(-?\d+),\s*(-?\d+)\},\s*(\w+)\}",tab[1]):
            gfx=65535 if g=="GFX_WATERTILE_SPECIALCHECK" else int(g)
            triplets.append((int(x),int(z),gfx))
        assert triplets and len(triplets)==tab[1].count("{{"),ref
        assert len({(x,z) for x,z,_ in triplets})==len(triplets),ref
        cell_count+=len(triplets)
        layout_count+=1
        out.append(f"    [{variant}]={{")
        for j in range(0,len(triplets),6):
            out.append("      "+",".join(f"{{{x},{z},{g}}}" for x,z,g in triplets[j:j+6])+",")
        out.append("    },")
    out.append("  },")
tile_specs=src.split("_origin_industry_tile_specs[NEW_INDUSTRYTILEOFFSET] = {",1)[1].split("\n};",1)[0]
tile_specs=re.sub(r"//[^\n]*|/\*.*?\*/","",tile_specs,flags=re.S)
masks={"SLOPE_W":1,"SLOPE_S":2,"SLOPE_E":4,"SLOPE_N":8,"SLOPE_STEEP":16}
slopes=[]
for row in re.findall(r"\{(.*?)\}",tile_specs,re.S):
    args_=[t.strip() for t in row.split(",")]
    assert len(args_) in (5,10),args_
    slopes.append(16 if len(args_)==5 else masks[args_[6]])
assert len(slopes)==175
out.append("  slope_refused={ -- Graphics-ID indexed construction restriction")
for j in range(0,len(slopes),16):
    out.append("    "+("[0]=" if j==0 else "")+",".join(map(str,slopes[j:j+16]))+",")
out.extend(("  },","}"))
data="\n".join(out)+"\n"
if args.check:
    assert OUT.read_text()==data,"The committed stock layout catalog differs from the RC1 table"
else:
    OUT.write_text(data)
print(f"PASS stock RC1 layout catalog: {len(types)} industry types, {layout_count} variants, {cell_count} records")
