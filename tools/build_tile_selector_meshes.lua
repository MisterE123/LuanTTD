-- Generate the visible ring around every legal OpenTTD terrain profile.
-- Run from the game root: lua5.1 tools/build_tile_selector_meshes.lua
local T=dofile("mods/luanttd_core/openttd/slope.lua")
local diagonal_we={[8]=true,[2]=true,[10]=true,[13]=true,[7]=true}
local layers={0,.009,.044,.053} -- in normalized tile coordinates
local corners={{0,0},{1,0},{1,1},{0,1}}
local function inset(edge,point)
  return {edge+(1-2*edge)*point[1],edge+(1-2*edge)*point[2]}
end
local function clip(poly,sign,crease)
  local kept={}
  local prev=poly[#poly]
  local d=sign*crease(prev)
  for _,p in ipairs(poly) do
    local nd=sign*crease(p)
    if (d<0 and nd>0) or (d>0 and nd<0) then
      local t=d/(d-nd)
      kept[#kept+1]={prev[1]+t*(p[1]-prev[1]),prev[2]+t*(p[2]-prev[2])}
    end
    if nd>=0 then kept[#kept+1]=p end
    prev,d=p,nd
  end
  return kept
end
for mask=0,30 do
  if mask<15 or mask==23 or mask==27 or mask==29 or mask==30 then
    local f=assert(io.open("mods/luanttd_core/models/bl_selector_"..mask..".obj","w"))
    f:write("# Generated by tools/build_tile_selector_meshes.lua\no TileOutline\nvt .25 .5\nvt .75 .5\n")
    local vcount=0
    local function crease(p)
      return diagonal_we[mask] and p[1]+p[2]-1 or p[1]-p[2]
    end
    local function height(p) return T.surface(p[1],p[2],mask) end
    local function emit(a,b,c,uv)
      local area=(b[1]-a[1])*(c[2]-a[2])-(b[2]-a[2])*(c[1]-a[1])
      if math.abs(area)<1e-10 then return end
      local x,z=(a[1]+b[1]+c[1])/3,(a[2]+b[2]+c[2])/3
      assert(math.abs((height(a)+height(b)+height(c))/3-T.surface(x,z,mask))<1e-8,
        "selector triangle crosses a slope crease")
      for _,p in ipairs({a,b,c}) do
        -- OBJ X is inverted by the Luanti importer; entity mesh scale is
        -- ten model units per node (different from mesh NODE scale).
        f:write(("v %.8g %.8g %.8g\n"):format(10-20*p[1],10*height(p),20*p[2]-10))
      end
      f:write(("f %d/%d %d/%d %d/%d\n"):format(vcount+1,uv,vcount+2,uv,vcount+3,uv))
      vcount=vcount+3
    end
    for band=1,#layers-1 do
      for i=1,4 do
        local a,b=corners[i],corners[i%4+1]
        local outside,inside=layers[band],layers[band+1]
        local strip={inset(outside,a),inset(outside,b),inset(inside,b),inset(inside,a)}
        for _,side in ipairs({-1,1}) do
          local half=clip(strip,side,crease)
          for j=2,#half-1 do emit(half[1],half[j],half[j+1],band==2 and 2 or 1) end
        end
      end
    end
    f:close()
  end
end
print("PASS: 19 exact profile-conforming tile-outline meshes")
