#!/usr/bin/env python3
"""Generate the playable farming/logging road rows from exact OpenTTD RC1."""
import argparse,hashlib,re
from pathlib import Path
ROWS=[
      (124,"coal_uhl","Uhl Coal Truck","coal"),
      (125,"coal_dw","DW Coal Truck","coal"),
      (126,"mail_mps","MPS Mail Truck","mail"),
      (127,"mail_reynard","Reynard Mail Truck","mail"),
      (128,"mail_perry","Perry Mail Truck","mail"),
      (133,"oil_foster","Foster Oil Tanker","oil"),
      (134,"oil_perry","Perry Oil Tanker","oil"),
      (140,"goods_goss","Goss Goods Truck","goods"),(135,"livestock_van","Talbott Livestock Van","livestock"),(136,"livestock_uhl","Uhl Livestock Van","livestock"),
      (137,"livestock_foster","Foster Livestock Van","livestock"),(141,"grain_truck","Hereford Grain Truck","grain"),
      (142,"grain_thomas","Thomas Grain Truck","grain"),(143,"grain_goss","Goss Grain Truck","grain"),
      (144,"wood_truck","Witcombe Wood Truck","wood"),(145,"wood_foster","Foster Wood Truck","wood"),
      (146,"wood_moreland","Moreland Wood Truck","wood"),
      (147,"iron_mps","MPS Iron Ore Truck","iron_ore"),(148,"iron_uhl","Uhl Iron Ore Truck","iron_ore"),
      (149,"iron_chippy","Chippy Iron Ore Truck","iron_ore"),
      (150,"steel_balogh","Balogh Steel Truck","steel"),(151,"steel_uhl","Uhl Steel Truck","steel"),
      (152,"steel_kelling","Kelling Steel Truck","steel"),
      (153,"valuables_balogh","Balogh Armoured Truck","valuables"),
      (154,"valuables_uhl","Uhl Armoured Truck","valuables"),
      (155,"valuables_foster","Foster Armoured Truck","valuables")]
def generate(p):
    d=p.read_bytes()
    assert hashlib.sha256(d).hexdigest()=="d90c9b2ae091a740522b0f79078c3e5db32b2467cb2a9e0e96592c3c39ee1f74"
    lines=["-- SPDX-License-Identifier: GPL-2.0-only",
           "-- OpenTTD contributors, exact RC1 engines.h. Generated by tools/build_road_farm_fleet_catalog.py.",
           "return {"]
    t=d.decode()
    for stock,k,name,cargo in ROWS:
        a=re.search(r"^\s*MR\(([^\n]+)\),\s*//\s*"+str(stock)+" "+name+r"\s*$",t,re.M)[1]
        b=re.search(r"^\s*ROV\(([^\n]+)\),\s*//\s*"+str(stock-116)+" "+name+r"\s*$",t,re.M)[1]
        intro,decay,life,base,label,*_=map(str.strip,a.split(","))
        assert label==({"grain":"MCT_GRAIN_WHEAT_MAIZE","valuables":"MCT_VALUABLES_GOLD_DIAMONDS"}.get(cargo,"CT_"+cargo.upper()))
        climate=re.search(r"LandscapeTypes\(\{([A-Z, ]+)\}\)",a)[1]
        bits=sum(2**"TASY".index(v) for v in climate if v in "TASY")
        im,price,run,_,speed,cap,weight,power=map(str.strip,b.split(","))
        lines.extend([f'  {k}={{stock_id={stock},vehicle_type=1,image={im},name="{name}",',
          f'    intro_after_1920={intro},decay_speed={decay},life={life},base_life={base},climates={bits},cargo="{cargo}",',
          f'    purchase_factor={price},running_factor={run},speed={speed},capacity={cap},weight_quarters={weight},power_tens_hp={power}}},'])
    return "\n".join(lines+["}",""])
if __name__=="__main__":
    p=argparse.ArgumentParser(description=__doc__);p.add_argument("engines",type=Path);p.add_argument("--write",action="store_true")
    args=p.parse_args()
    target=Path(__file__).resolve().parents[1]/"mods/luanttd_core/openttd/road_farm_fleet_data.lua"
    text=generate(args.engines)
    reference=args.engines.read_text()
    stock_bus=re.search(r"^\s*MR\(\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+).*// 119 Foster MkII Superbus$",reference,re.M)
    road=re.search(r"^\s*ROV\(([^\n]+)\), //\s+3 Foster MkII Superbus$",reference,re.M)
    assert tuple(map(int,stock_bus.groups()))==(32142,20,15,80)
    cells=list(map(str.strip,road[1].split(",")))
    assert [int(cells[i]) for i in (0,1,2,4,5,6,7)]==[34,160,240,255,40,100,25]
    assert re.search(r"^#define MR.+, b, 5, f,",reference,re.M),"Source loading amount moved"
    if args.write:target.write_text(text)
    else:
        assert target.read_text()==text
        print("PASS indexed exact RC1 road stock rows, plus Foster MkII")
