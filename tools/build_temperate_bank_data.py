#!/usr/bin/env python3
"""Extract the Temperate Bank (not ID 16) and stock Valuables from RC1."""
from argparse import ArgumentParser
from pathlib import Path
import re
from build_iron_steel_data import pin

def generate(source):
    industries = pin(source, "build_industry.h")
    cargo = pin(source, "cargo_const.h")
    kind = int(re.search(r"\bIT_BANK_TEMP\s*=\s*(\d+),", industries)[1])
    layout = re.search(r"_tile_table_bank_0\s*\{(.*?)\n\};", industries, re.S)[1]
    cells = re.findall(r"\{\{(\d+),\s*(\d+)\},\s*(\d+)\}", layout)
    assert kind == 12 and len(cells) == 2
    row = re.search(r"\bMI\(_tile_table_bank,\s*\{\},(.*?)STR_INDUSTRY_NAME_BANK", industries, re.S)[1]
    cost, prob, *weights = map(str.strip, row.strip().splitlines()[0].split(","))
    assert "INDUSTRYLIFE_BLACK_HOLE" in row and "LandscapeType::Temperate" in row and "Town1200More" in row
    assert re.search(r"IT_BANK_TEMP,\s+IT_INVALID,", row)
    rate, minimum, multiplier = re.search(
        r"MCT_VALUABLES_GOLD_DIAMONDS,\s*(\d+),\s*CT_INVALID,\s*0,\s*(\d+),\s*"
        r"MCT_VALUABLES_GOLD_DIAMONDS,\s*(\d+),", row
    ).groups()
    idx, colour, weight, cap, price, d1, d2 = re.search(
        r"\bMK\(\s*(\d+), CT_VALUABLES,\s*(\d+),\s*(\d+),\s*(0x\w+),\s*(\d+),\s*(\d+),\s*(\d+),",
        cargo,
    ).groups()
    tiles = industries.split("/* Bank temperate*/",1)[1].split("/*",1)[0]
    assert re.findall(r"\{1, CT_PASSENGERS, 8, MCT_VALUABLES_GOLD_DIAMONDS, 0, CT_INVALID, (SLOPE_\w+),", tiles) == ["SLOPE_E", "SLOPE_S"]
    return "\n".join([
        "-- SPDX-License-Identifier: GPL-2.0-only",
        "-- OpenTTD contributors: 16.0-RC1 build_industry.h and cargo_const.h.",
        "-- Generated by tools/build_temperate_bank_data.py.",
        "return {",
        "  layout={[0]={"+ ",".join("{" + ",".join(line) + "}" for line in cells) + "}},",
        f'  spec={{id={kind},life="black_hole",minimum={minimum},cost_factor={cost},procurement_probability={prob},',
        f'    climates=1,sounds=0,out={{"valuables"}},rates={{{rate}}},input={{"valuables"}},multiplier={{{multiplier}}},',
        f'    appearance={{{",".join(weights[:4])}}},generation={{{",".join(weights[4:8])}}},map_colour={weights[8]}}},',
        f'  cargo={{id={idx},label="VALU",class="armoured",weight_16={weight},capacity_multiplier={int(cap,16)},',
        f'    payment={price},days1={d1},days2={d2},colour={colour}}},',
        "  tile_acceptance={passenger=1,valuables=8},",
        "  refuses_slopes={[58]=4,[59]=2}, -- OpenTTD east and south corners.",
        "}", "",
    ])

if __name__ == "__main__":
    parser=ArgumentParser(description=__doc__)
    parser.add_argument("source",type=Path);parser.add_argument("--write",action="store_true")
    args=parser.parse_args()
    target=Path(__file__).resolve().parents[1]/"mods/luanttd_core/openttd/temperate_bank_data.lua"
    data=generate(args.source)
    if args.write: target.write_text(data)
    else:
        assert target.read_text()==data
        print("PASS pinned RC1 Temperate Bank and Valuables source rows")
