#!/usr/bin/env python3
"""Extract the RC1 Iron Mine/Steel Mill and both stock cargo rows."""
from argparse import ArgumentParser
from hashlib import sha256
from pathlib import Path
import re

PIN={
    "build_industry.h":"eb7938fd37dd37854927253f2f3beeed3c6cafa7425d959035cefef149b66056",
    "cargo_const.h":"cac711a29f0bcd906a8c202219ead4ba5cec90bfc5ea2e2fc03c990ab86f43d2",
}

def pin(base,name):
    blob=(base/name).read_bytes()
    assert sha256(blob).hexdigest()==PIN[name],name
    return blob.decode()

def generate(source):
    s=pin(source,"build_industry.h")
    c=pin(source,"cargo_const.h")
    out=["-- SPDX-License-Identifier: GPL-2.0-only",
         "-- OpenTTD contributors: 16.0-RC1 build_industry.h and cargo_const.h.",
         "-- Generated by tools/build_iron_steel_data.py; see pinned source there.",
         "return {","  layout={"]
    for name,prefix,layouts in (("iron_mine","iron_mine",1),("steel_mill","steel_mill",2)):
        out += [f"    {name}={{"]
        for i in range(layouts):
            b=re.search(rf'_tile_table_{prefix}_{i}\s*\{{(.*?)\n\}};',s,re.S)[1]
            cells=re.findall(r'\{\{(\d+),\s*(\d+)\},\s*(\d+)\}',b)
            assert len(cells)==({("iron_mine",0):16,("steel_mill",0):12,("steel_mill",1):14})[name,i]
            assert len({(v[0],v[1]) for v in cells})==len(cells)
            out += ['      ['+str(i)+']={'+','.join('{'+','.join(v)+'}' for v in cells)+'},']
        out+=["    },"]
    out+=["  },","  spec={"]
    for name,constant,prod,inp,op in (("iron_mine","IRON_MINE","iron_ore",None,"Extractive"),
                                      ("steel_mill","STEEL_MILL","steel","iron_ore","Processing")):
        idx=int(re.search(rf'\bIT_{constant}\s*=\s*(\d+),',s)[1])
        b=re.search(rf'\bMI\(_tile_table_{name},\s*\{{\}},(.*?)STR_INDUSTRY_NAME_',s,re.S)[1]
        cost,prob,*rest= map(str.strip,b.strip().splitlines()[0].split(',')) if b.strip() else []
        appearance=list(map(int,rest[:4]));generation=list(map(int,rest[4:8])); colour=int(rest[8])
        p=re.search(r'CT_'+prod.upper()+r',\s*(\d+),\s*CT_INVALID,\s*0,\s*(\d+),',b)
        rate,minimum=map(int,p.groups())
        if inp: assert re.search(rf'CT_{inp.upper()},\s*256,',b[p.end():])
        assert 'IndustryLifeType::'+op in b and 'LandscapeType::Temperate' in b
        fields=[f'id={idx}',f'life="{op.lower()}"',f'minimum={minimum}',f'cost_factor={cost}',
          f'procurement_probability={prob}',f'climates=1',f'sounds=0',f'out={{"{prod}"}}',f'rates={{{rate}}}',
          'input={"iron_ore"}' if inp else 'input={}','multiplier={256}' if inp else 'multiplier={}',
          'appearance={'+','.join(map(str,appearance))+'}','generation={'+','.join(map(str,generation))+'}',f'map_colour={colour}']
        out += [f"    {name}={{"+",".join(fields[:8])+",", "      "+",".join(fields[8:])+"},"]
    out += ["  },","  cargo={"]
    for name,token,label,kind in (("iron_ore","CT_IRON_ORE","IORE","bulk"),("steel","CT_STEEL","STEL","piece_goods")):
        row=re.search(rf'\bMK\(\s*([\d, ]+),\s*{token}\s*,\s*([\d, x]+),\s*true',c)
        idx=int(row[1])
        colour,weight,cap,price,a,b=list(map(str.strip,row[2].split(',')))
        out += [f'    {name}={{id={idx},label="{label}",class="{kind}",weight_16={weight},capacity_multiplier={int(cap,16)},',
                f'      payment={price},days1={a},days2={b},colour={colour}}},']
    return "\n".join(out+["  },","}",""])

if __name__=="__main__":
    p=ArgumentParser(description=__doc__);p.add_argument('source',type=Path);p.add_argument('--write',action='store_true')
    a=p.parse_args()
    target=Path(__file__).resolve().parents[1]/"mods/luanttd_core/openttd/iron_steel_data.lua"
    expected=generate(a.source)
    if a.write:target.write_text(expected)
    else:
        assert target.read_text()==expected
        print("PASS pinned RC1 layouts, industry specifications and Iron Ore/Steel cargo")
