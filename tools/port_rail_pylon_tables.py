#!/usr/bin/env python3
"""Extract RC1's enum-indexed catenary tables as numeric Lua arrays."""
import re
import subprocess
import sys
from pathlib import Path

upstream = Path(sys.argv[1])
assert subprocess.check_output(["git", "-C", upstream, "rev-parse", "HEAD"], text=True).strip() == "07b339c0aaeb0a87be9490b2f1c3f17c6b00b837"
raw = (upstream / "src/table/elrail_data.h").read_text()
raw = re.sub(r"/\*.*?\*/|//[^\n]*", "", raw, flags=re.S)
dirs = dict(zip(("N","NE","E","SE","S","SW","W","NW"), range(8)))
tracks = dict(zip(("X","Y","Upper","Lower","Left","Right"), range(6)))

def block(name):
    a = raw.index(name)
    return raw[a:raw.index(";", a)]

def leaf(name):
    return re.findall(r"\{([^{}]*)\}|(DIRECTIONS_ALL)", block(name))

def dirmasks(name):
    return [255 if full else sum(1 << dirs[x] for x in re.findall(r"Direction::(\w+)", row)) for row,full in leaf(name)]

def inner(name,typ,key):
    return [[key[x] for x in re.findall(typ+r"::(\w+)", row)] for row,_ in leaf(name)]

def group(rows, width):
    assert len(rows)%width==0
    return [rows[i:i+width] for i in range(0,len(rows),width)]

def offs(name):
    return list(map(int,re.findall(r"-?\d+",leaf(name)[0][0])))

arrays = {
  "allowed": dirmasks("_allowed_ppp_on_pcp"),
  "owned": dirmasks("_owned_ppp_on_pcp"),
  "preferred": group(dirmasks("_preferred_ppp_of_track_at_pcp"),4),
  "ignored": group(group(dirmasks("_ignored_pcp"),4),4),
  "blocked": group(dirmasks("_disallowed_ppp_of_track_at_pcp"),4),
  "tracks": inner("_tracks_at_pcp", "Track", tracks),
  "source": inner("_track_source_tile", "TileSource", {"Home":0,"Neighbour":1}),
  "order": group(inner("_ppp_order", "Direction", dirs),4),
  "pcp_x": offs("_x_pcp_offsets"),
  "pcp_z": offs("_y_pcp_offsets"),
  "ppp_x": offs("_x_ppp_offsets"),
  "ppp_z": offs("_y_ppp_offsets"),
}
assert len(arrays["allowed"])==len(arrays["owned"])==len(arrays["tracks"])==len(arrays["order"])==4
assert len(arrays["preferred"])==len(arrays["blocked"])==6 and len(arrays["ignored"])==3
assert all(len(x)==8 for row in arrays["order"] for x in row)

def lua(x):
    return "{"+",".join(map(lua,x))+"}" if isinstance(x,list) else str(x)

print("-- SPDX-License-Identifier: GPL-2.0-only")
print("-- OpenTTD 16.0-RC1 table/elrail_data.h, generated by tools/port_rail_pylon_tables.py.")
print("return {")
for k,v in arrays.items():
    print(f"  {k}={lua(v)},")
print("}")
