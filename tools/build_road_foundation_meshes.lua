-- Produce original masonry side faces below unchanged source-derived road ramps.
-- Run from game root with Lua 5.1. The color atlas reserves its left half for asphalt, right half for stone.
local slope=dofile("mods/luanttd_core/openttd/slope.lua")
local uv={{0,0},{1,0},{1,1},{0,1}} -- clockwise viewed from above after Luanti's OBJ X flip
for _,mask in ipairs{3,6,9,12} do
  local out=assert(io.open(("mods/luanttd_core/models/bl_road_grade_foundation_%d.obj"):format(mask),"w"))
  local h={}
  out:write("# Generated by tools/build_road_foundation_meshes.lua\no Road grade\n")
  for i,p in ipairs(uv) do
    h[i]=slope.surface(p[1],p[2],mask)
    out:write(("v %g %g %g\n"):format(.5-2*p[1],h[i]-.5,2*p[2]-.5))
  end
  -- Reuse the top vertex at low corners so no degenerate masonry triangles.
  local foot,n={},4
  for i,p in ipairs(uv) do
    if h[i]>0 then
      n=n+1;foot[i]=n
      out:write(("v %g -0.5 %g\n"):format(.5-2*p[1],2*p[2]-.5))
    else foot[i]=i end
  end
  -- Sample texel centers at 32px region borders; never bleed another
  -- material into a road shoulder or a face boundary.
  for _,u0 in ipairs{0,32} do
    for _,p in ipairs(uv) do
      out:write(("vt %.9f %.9f\n"):format((u0+.5+31*p[1])/64,(31.5-31*p[2])/32))
    end
  end
  out:write("# road surface\nf 1/1 2/2 3/3\nf 1/1 3/3 4/4\n# retaining sides\n")
  for a=1,4 do
    local b=a%4+1
    -- Whole-height edge has two faces. Each end is triangular; low edge
    -- has no wall. The wedge ends exactly at the backing cube's top.
    if h[a]>0 then out:write(("f %d/5 %d/8 %d/7\n"):format(a,foot[a],foot[b])) end
    if h[b]>0 then out:write(("f %d/%d %d/7 %d/6\n"):format(a,h[a]>0 and 5 or 8,foot[b],b)) end
  end
  out:close()
end
