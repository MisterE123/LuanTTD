function S.departure(mode,engine,tick,helicopter)
  if mode=="air" and helicopter then return S.sample.TAKEOFF_HELICOPTER end
  local t=mode=="rail" and rail or mode=="road" and road or mode=="ship" and ship or mode=="air" and air
  local fx=t and t[engine]
  if fx==S.sample.DEPARTURE_OLD_RV_1 and tick and tick%4==0 then
    return S.sample.DEPARTURE_OLD_RV_2
  end
  return fx
end
return S
