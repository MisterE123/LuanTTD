local function population_bits(n)
  local out=0
  while n>0 do out=out+n%2;n=math.floor(n/2) end
  return out
end
function T.sample(tile,gx,gz,species,count,growth)
  assert(species>=0 and species<12 and count>=1 and count<=4 and growth>=0 and growth<=6)
  -- ti->x and ti->y are tile origin in OpenTTD's 16-pixel units.
  -- tile, gx and gz are zero-based. No RNG, sorting or state mutation.
  local mixed=population_bits(tile+16*(gx+gz))
  local forms=sprite_base[species*4+mixed%4+1]
  local offsets=stem_offset[math.floor(mixed/4)%4+1]
  local out={}
  for i=1,count do
    out[i]={shape=forms[i],dx=offsets[i][1],dz=offsets[i][2],phase=i==count and growth or 3}
  end
  return out
end
return T
