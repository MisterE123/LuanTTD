local R=dofile("mods/bayline/openttd/road_slope.lua")
local S=dofile("mods/bayline/openttd/slope.lua")
local b,fee=R.prepare(3,8,0,0,true) -- SLOPE_SW, ROAD_NE
assert(b==10 and fee==false and R.foundation(3,b)=="none","autocompletes uphill")
b,fee=R.prepare(3,5,0,0,true)
assert(b==5 and fee==true and R.foundation(3,b)=="leveled","across slope needs foundation")
b,fee=R.prepare(3,1,10,0,true)
assert(b==nil and fee=="WRONG_SLOPE","reject branch across slope from uphill road")
assert(not R.prepare(3,5,0,0,false))
b,fee=R.prepare(30,2,0,0,true)
local f=R.foundation(30,b)
local h,dz=S.foundation(30,f)
assert(b==10 and fee==true and f=="x" and h==12 and dz==1,"steep inclined foundation")
assert(R.prepare(0,15,5,0,true)==10)
assert(not R.prepare(0,1,1,0,true))
print("PASS: three OpenTTD slope road fixtures, steep foundation, flat additions, and rejection")
