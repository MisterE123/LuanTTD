rng=Random(16003)
cases=[]
for climate,count in [(0,12000),(1,6000),(2,6000),(3,6000)]:
    for _ in range(count):
        cases.append([rng.randrange(1,180),rng.randrange(-8,9),rng.randrange(-8,9),rng.randrange(4),
            rng.randrange(2),rng.randrange(2),rng.randrange(2),rng.choice([-1]*3+[rng.randrange(110)]),
            rng.randrange(1900,2051),rng.choice([0]*4+[1]),climate,rng.randrange(2),
            *[rng.choice([0]*12+[1,2,3,4,5,6,7,7]) for _ in range(9)],
            *[rng.getrandbits(32) for _ in range(112)]])
data="".join(" ".join(map(str,row))+"\n" for row in cases)
with TemporaryDirectory(prefix="town-house-rc1-") as work:
    d=Path(work)
    (d/"ref.cpp").write_text(cpp)
    (d/"test.lua").write_text(program)
    subprocess.run([os.environ.get("CXX","c++"),"-std=c++20","-O2",d/"ref.cpp","-o",d/"ref"],check=True)
    catalog=catalog_header+subprocess.check_output([d/"ref","catalog"],text=True)+"}\n"
    if "--write-catalog" in sys.argv[3:]:
        catalog_path.write_text(catalog)
        sys.exit(0)
    assert catalog_path.read_text()==catalog,"Climate house roster differs from the pinned source"
    ref=subprocess.check_output([d/"ref"],text=True,input=data).splitlines()
    port=subprocess.check_output([lua,d/"test.lua"],text=True,input=data).splitlines()
    assert len(ref)==len(port)==len(cases)
    selected=[set() for _ in range(4)]
    for case,line in zip(cases,ref):
        selected[case[10]].add(int(line.split()[0]))
    assert len(selected[0])>=30 and {-1,0x07,0x14,0x20,0x28}<=selected[0], selected[0]
    assert all(len(q)-1>=n and -1 in q for q,n in zip(selected,(31,35,20,18))), selected
    errors=[(i,cases[i][:19],a,b) for i,(a,b) in enumerate(zip(ref,port)) if a.split()!=b.split()]
    assert not errors,(len(errors),errors[:6])
print(f"PASS {len(cases)} exact RC1 house cases across four climates (distinct built roots:"
      f" {[len(q)-1 for q in selected]})")
