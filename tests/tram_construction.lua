local root="mods/luanttd_core/openttd/"
local B=dofile(root.."road_bridge.lua")(dofile(root.."slope.lua"))
local T=dofile(root.."tram_construction.lua")(dofile(root.."road_slope.lua"),B.roadtypes)
local rt=1
local o={owner="A"}
local function fails(why,f,...)
  local plan,msg=f(...)
  assert(not plan and msg==why,("%s vs %s"):format(tostring(msg),why))
end
assert(B.roadtypes[rt].label=="ELRL" and B.roadtypes[rt].flags==5
   and B.roadtypes[rt].powered[rt] and not B.roadtypes[rt].powered[0])
local t={kind="road",roadtype=0,road_bits=10,road_owner="town"}
local p=assert(T.lay(t,2,rt,o))
assert(p.cost==190 and p.tram_bits==2 and p.tram_owner=="A")
assert(p.road_bits==10 and p.road_owner=="town" and t.tramtype==nil)
p=assert(T.lay({kind="road",roadtype=0,road_bits=10,road_owner="B",disallowed=3},5,rt,o))
assert(p.tram_bits==5 and p.cost==380 and p.road_owner=="B")
fails("OWNED_BY_ANOTHER",T.lay,{kind="road",tramtype=1,tram_bits=8,tram_owner="B"},2,rt,o)
p=assert(T.lay({kind="road",tramtype=1,tram_bits=10,tram_owner="B"},2+4,rt,o))
assert(p.tram_bits==14 and p.tram_owner=="B" and p.cost==190)
fails("ROAD_WORKS_IN_PROGRESS",T.lay,{kind="road",roadworks=true},2,rt,o)
fails("VEHICLE_IN_THE_WAY",T.lay,{kind="road",occupied=true},2,rt,o)
fails("WRONG_SLOPE",T.lay,{kind="road",slope=3,roadtype=0,road_bits=10},5,rt,o)
fails("ROADTYPE_NOT_FOR_TOWN",T.lay,{kind="clear"},10,rt,{owner="town",town_generation=true})
fails("INVALID_PARAMETER",T.lay,{kind="clear"},10,rt,{owner="A",available=function() return false end})
fails("WATER",T.lay,{kind="water"},10,rt,{owner="A",no_water=true})

p=assert(T.lay({kind="rail",rail_axis=1,owner="B"},2,rt,o))
assert(p.kind=="crossing" and p.axis==0 and p.tram_bits==10 and p.cost==380 and p.roadtype==nil and p.rail_owner=="B")
fails("WRONG_SLOPE",T.lay,{kind="rail",rail_axis=1,slope=6},2,rt,o)
fails("CROSSING_DISALLOWED_RAIL",T.lay,{kind="rail",rail_axis=1,rail_no_crossing=true},2,rt,o)
fails("OWNED_BY_ANOTHER",T.lay,{kind="rail",rail_axis=1,owner="B"},2,rt,{owner="A",crossing_with_competitor=false})
p=assert(T.lay({kind="crossing",axis=0,roadtype=0,road_bits=10,road_owner="B"},2,rt,o))
assert(p.road_bits==10 and p.tram_bits==10 and p.road_owner=="B" and p.cost==380)

fails("TRAM_DRIVE_THROUGH_ONLY",T.stop,t,0,rt,{owner="A",drive_through=false})
p=assert(T.stop(t,0,rt,o))
assert(p.cost==580 and p.roadtype==0 and p.road_owner=="town" and p.tramtype==1 and p.tram_owner=="A")
assert(p.tram_bits==10 and p.road_bits==10 and not t.tramtype)
fails("DRIVE_THROUGH_ON_TOWN_ROAD",T.stop,t,0,rt,{owner="A",on_town_road=false})
fails("DRIVE_THROUGH_DIRECTION",T.stop,t,1,rt,o)
fails("DRIVE_THROUGH_CORNER",T.stop,{kind="road",roadtype=0,road_bits=12},0,rt,o)
fails("DRIVE_THROUGH_JUNCTION",T.stop,{kind="road",roadtype=0,road_bits=11},0,rt,o)
fails("OWNED_BY_ANOTHER",T.stop,{kind="road",tramtype=1,tram_bits=8,tram_owner="B"},0,rt,o)
fails("OWNED_BY_ANOTHER",T.stop,{kind="road",roadtype=0,road_bits=10,road_owner="B",disallowed=1},0,rt,o)
p=assert(T.stop({kind="road",tramtype=1,tram_bits=8,tram_owner="A"},0,rt,o))
assert(p.cost==390 and p.tram_bits==10 and not p.roadtype)
p=assert(T.stop({kind="road",tramtype=1,tram_bits=10,tram_owner="B"},0,rt,o))
assert(p.cost==200 and p.tram_owner=="B" and p.owner=="A")
p=assert(T.stop({kind="clear",base=2,slope=5},0,rt,{owner="A",allowed_z=3}))
assert(p.cost==830 and p.base==3 and p.tram_bits==10)
fails("FLAT_LAND_REQUIRED",T.stop,{kind="clear",slope=0},0,rt,{owner="A",allowed_z=1})
fails("FLAT_LAND_REQUIRED",T.stop,{kind="clear",slope=6},1,rt,o)
fails("MUST_DEMOLISH_BRIDGE_FIRST",T.stop,{kind="clear",overhead=true},0,rt,o)

p=assert(T.depot({kind="clear",slope=12},0,rt,o))
assert(p.cost==750 and p.dir==0 and p.tram_bits==8 and not p.roadtype and p.foundation=="leveled")
fails("FLAT_LAND_REQUIRED",T.depot,{kind="clear",slope=3},0,rt,o)
fails("MUST_DEMOLISH_BRIDGE_FIRST",T.depot,{kind="clear",overhead=true},0,rt,o)
p=assert(T.depot({kind="depot",tramtype=1,dir=0,owner="A",overhead=true},2,rt,o))
assert(p.rotate and p.cost==500 and p.tram_bits==2)
fails("OWNED_BY_ANOTHER",T.depot,{kind="depot",tramtype=1,dir=0,owner="B"},2,rt,o)
fails("LANDSCAPE_CLEAR_REQUIRED",T.depot,{kind="depot",roadtype=0,dir=0,owner="A"},2,rt,o)

local portal={kind="bridge",transport="road",dir=0,skip=6,roadtype=0,road_owner="A"}
p=assert(T.lay(portal,2,rt,o))
assert(p.cost==3040 and p.roadtype==0 and p.tram_bits==2)
portal.span_occupied=true
fails("VEHICLE_IN_THE_WAY",T.lay,portal,2,rt,o)
assert(T.effective_bits({kind="bridge",transport="road",dir=1,tramtype=1},true)==5)
assert(T.effective_bits({kind="bridge",transport="road",dir=1,tramtype=1},false)==1)
assert(T.effective_bits({kind="road",roadtype=0,road_bits=10,overhead=true},true)==0)
print("PASS: ELRL & pavement layers/ownership, crossings, same-axis drive stops, depot grades and paired-bridge overlay quotes")
