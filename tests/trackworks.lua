local Sim=dofile("mods/luanttd_core/sim.lua")
local Track=dofile("mods/luanttd_core/openttd/rail_track.lua")
local Follow=dofile("mods/luanttd_core/openttd/rail_follow.lua")(Track)
local Costs=dofile("mods/luanttd_core/openttd/rail_yapf_cost.lua")(Track,Follow)
local Search=dofile("mods/luanttd_core/openttd/rail_yapf_search.lua")(Track,Follow,Costs)
local Lab=dofile("mods/luanttd_core/trackworks.lua")(Sim,Track,Follow,dofile("mods/luanttd_core/openttd/slope.lua"),Costs,Search)
local s=Sim.new(42)
local function prepare(x,z)
  local i=Sim.id(x,z)
  local t=s.tiles[i]
  t.terrain,t.h,t.build,t.site,t.house,t.owner,t.wood="grass",0,nil,nil,nil,nil,nil
  return i
end
local a,b,c,d=prepare(15,15),prepare(16,15),prepare(16,16),prepare(17,15)
assert(not Lab.change(s,"A",a,Track.X,false,nil))
assert(Lab.change(s,"A",a,Track.X,false,0))
assert(Lab.change(s,"A",b,Track.RIGHT,false,0))
assert(Lab.change(s,"A",c,Track.Y,false,0))
assert(not Lab.change(s,"B",b,Track.LOWER,false,0))
local mask,connected=Lab.inspect(s,b,"A")
assert(mask==32 and connected==2)
local course,cost=Lab.plan(s,a,c,"A")
assert(course and #course==3 and course[1].tile==a and course[2].tile==b and course[3].tile==c and cost>0)
assert(Lab.change(s,"A",b,Track.X,false,0))
assert(Lab.change(s,"B",d,Track.X,false,0))
assert(not Lab.plan(s,a,d,"A"))
mask,connected=Lab.inspect(s,b,"A")
assert(mask==33 and connected==3,connected)
assert(Lab.change(s,"A",b,Track.RIGHT,true,0))
assert(Sim.build(s,"A","clear",{b}) and not s.tiles[b].rail_tracks)
local g,base,kind,profile=Lab.surface(3,2,1)
assert(g==1 and base==2 and kind=="none" and profile==3)
g,base,kind,profile=Lab.surface(1,2,1)
assert(g==1 and base==2 and kind=="x" and profile==3)
assert(not Lab.surface(5,2,1+2) or Lab.surface(5,2,1+2)==0)
print("PASS: explicit stock pieces, owned rail transitions, curve joins and bulldozer")

local first,last,mid,near,far,finish=prepare(21,18),prepare(22,18),prepare(23,18),prepare(24,18),prepare(25,18),prepare(26,18)
for _,id in ipairs({first,last,mid,near,far,finish}) do assert(Lab.change(s,"A",id,Track.X,false,0)) end
assert(not Lab.depot(s,"A",last,Track.SW))
assert(Lab.depot(s,"A",first,Track.SW))
assert(not Lab.station(s,"B",near,far))
assert(Lab.station(s,"A",far,near))
assert(not Sim.build(s,"A","clear",{near}))
assert(not Lab.change(s,"A",near,Track.X,true,0))
local board=Lab.board(s)
assert(board.tile(first).dir==Track.SW)
assert(board.tile(near).station==board.tile(far).station)
local station=board.tile(near).station
local test,cost=Lab.service_route(s,"A",{tile=first},station)
assert(test and #test==5 and test[4].tile==near and test[5].tile==far and cost>0)
assert(not Lab.service_route(s,"A",{tile=first,td=0},station))
assert(not Lab.service_route(s,"B",{tile=first},station))
assert(not Lab.remove_facility(s,"B",far))
assert(Lab.remove_facility(s,"A",far))
assert(not board.tile(near).station and not board.tile(far).station)
assert(not Lab.service_route(s,"A",{tile=first},station))
assert(Sim.build(s,"A","clear",{near}))
print("PASS: atomic real platforms, portal orientation, owner validation, multi-tile YAPF expansion and removal")
