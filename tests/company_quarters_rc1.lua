local Q=dofile("mods/luanttd_core/openttd/company_quarters_rc1.lua")
local H=dofile("mods/luanttd_core/openttd/company_hq_rc1.lua")
local c={cash=100000,loan=50000}
Q.money(c,"rail_income",-93151)
Q.money(c,"loan_interest",173)
Q.money(c,"rail_run",120)
Q.money(c,"property",100)
Q.money(c,"rail_wagon_purchase",8690)
Q.money(c,"construction",12091)
Q.delivered(c,"coal",100)
Q.delivered(c,"coal",350)
Q.delivered(c,"mail",12)
assert(not Q.month(c,1950,2))
local april=assert(Q.month(c,1950,4))
assert(april.income==93151 and april.expenses==-393 and april.delivered.coal==450)
assert(not Q.month(c,1950,4) and #c.stock_quarters==1 and not c.stock_quarter)
Q.delivered(c,"mail",3)
Q.delivered(c,"passengers",99)
local july=assert(Q.month(c,1950,7))
assert(july.delivered.mail==3 and c.stock_quarters[2]==april)
local p,split=H.score(c,{},{{facilities=1,time_since_load=18}},c.stock_quarters,730)
assert(p>0 and split.stations==1 and split.delivered==564 and split.cargo==2 and split.min_income==0)
for y=1951,1979 do Q.month(c,y,1) end
assert(#c.stock_quarters==24)
print("PASS RC1 scored operating expenses, cargo diversity, 24-quarter rollover and no construction leakage")
