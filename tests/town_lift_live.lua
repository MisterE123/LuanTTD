local p="mods/luanttd_core/"
local function m(x)return dofile(p..x..".lua")end
local S=m("sim");S.W,S.H=64,64
local Terrain=m("openttd/terrain")
local H=m("openttd/town_passengers")
local P=m("openttd/passengers")
local R=m("station_rating_runtime")(S,m("openttd/station_rating"),P)
local M=m("town_passenger_runtime")(S,H,P,R)
local Codec=m("packed_campaign")
local L=m("openttd/town_lift")
local TP=m("campaign_terrain_projection")
local s=S.new(1751)
for id in pairs(s.tiles) do s.tiles[id]={terrain="grass",h=1,variant=0} end
s.corner_grid=Terrain.new(64,64,function() return 1 end)
s.stock_town_lifts=L.new()
local id=S.id(8,8)
local h={id=0x04,x=8,z=8,town=1,root=true,completed=true,stage=3}
s.tiles[id].house,s.tiles[id].source_house=true,h
local remote=S.id(53,51)
s.tiles[remote].house,s.tiles[remote].source_house=true,{id=0x04,x=53,z=51,town=1,completed=true}
L.install(s.stock_town_lifts,id,S)
L.install(s.stock_town_lifts,remote,S)
local projected=TP.tile(s.tiles[id])
assert(projected.source_house.lift_position==nil)
M.day(s)
assert(h.lift_position>0 and h.lift_has_destination and s.passenger_house_clock.counter==74)
assert(TP.matches_tile(s.tiles[id],projected),"Lift steps must not dirty terrain snapshots")
local local_pos=L.visible(s.stock_town_lifts,S,s.tiles,1,1,10,10)
assert(local_pos[id]==h.lift_position and not local_pos[remote])
local save=Codec.decode(Codec.encode(s))
assert(save.tiles[id].source_house.lift_position==h.lift_position)
assert(save.stock_town_lifts.order[1]==id and save.stock_town_lifts.order[2]==remote)
M.day(save);M.day(s)
assert(s.tiles[id].source_house.lift_position==save.tiles[id].source_house.lift_position)
assert(s.passenger_rating_rng[1]==save.passenger_rating_rng[1] and s.passenger_rating_rng[2]==save.passenger_rating_rng[2])
local V=m("campaign_authority_projection")()
local a,b=V.subscribe("a"),V.subscribe("b")
local function put(key,token,seq,tick,value)
  assert(V.accept(key,token,{ok=true,seq=seq,tick=tick,value={town_lifts=value}}))
end
put("a",a,4,2,{[id]=2})
put("b",b,7,3,{[id]=3,[remote]=20})
assert(V.town_lifts()[id]==3 and V.town_lifts()[remote]==20)
V.unsubscribe("a")
assert(not V.accept("a",a,{ok=true,seq=8,value={town_lifts={[id]=9}}}))
V.unsubscribe("b")
assert(next(V.town_lifts())==nil)
L.erase(save.stock_town_lifts,id)
assert(not L.visible(save.stock_town_lifts,S,save.tiles,1,1,10,10)[id])
print("PASS authority lift timing, packed RNG replay, bounded motion-only observation and disposal")
